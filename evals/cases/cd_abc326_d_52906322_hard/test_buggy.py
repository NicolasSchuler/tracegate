import subprocess
import sys


def test_condefects_0():
    proc = subprocess.run(
        [sys.executable, "buggy.py"],
        input='5\nABCBC\nACAAB\n',
        capture_output=True,
        text=True,
        timeout=10,
    )
    expected = 'Yes\nAC..B\n.BA.C\nC.BA.\nBA.C.\n..CBA\n'
    actual = proc.stdout.strip()
    assert actual == expected.strip(), (
        f"Expected {expected.strip()!r}, got {actual!r}"
    )


